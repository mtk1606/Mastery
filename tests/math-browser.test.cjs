'use strict';
const assert=require('node:assert/strict'),{chromium}=require('playwright');
(async()=>{
 const base='http://127.0.0.1:8901/';
 const browser=await chromium.launch({headless:true});
 const ctx=await browser.newContext({viewport:{width:1366,height:900},reducedMotion:'reduce',acceptDownloads:true});
 await ctx.addInitScript(()=>localStorage.setItem('mastery-theme','dark'));
 const page=await ctx.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 const chapters=['c3-proofs','c3-counting','c3-expect','c3-variance','c3-linear','c3-opt'];
 for(const id of chapters){
  await page.goto(base+'foundation.html#C3/'+id,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(key=>document.querySelector('.mv-top h4')?.textContent===window.MasteryVisualScenes.lookup(key)?.title,id);
  assert.equal(await page.locator('.mv-svg').count(),1,id+' needs one visual');
  assert.equal(await page.locator('.mv-svg').getAttribute('role'),'img');
  assert((await page.locator('.mv-svg title').textContent()).length>=20);
  assert((await page.locator('.mv-svg desc').textContent()).length>=55);
  assert.equal(await page.locator('.mv-option').count(),3);
  await page.locator('[data-mv-action="next"]').click();
  assert.match(await page.locator('.mv-count').textContent(),/02/);
  await page.locator('[data-mv-action="mode-text"]').click();
  assert((await page.locator('.mv-steps li').count())>=3);
  await page.locator('[data-mv-action="mode-visual"]').click();
  assert.equal(await page.locator('.mv-svg').count(),1);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 }
 await page.goto(base+'foundation.html#C3/c3-proofs',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="induction"]').selectOption('6');
 assert.match(await page.locator('.mv-explanation p').textContent(),/25/);
 await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/11/);
 await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/36/);
 await page.goto(base+'foundation.html#C3/c3-counting',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="bayes"]').selectOption('25');
 assert.match(await page.locator('.mv-question').textContent(),/225 true positives and 75 false positives/);
 for(let i=0;i<4;i++)await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/75.00%/);
 await page.locator('[data-mv-action="answer"][data-mv-choice="1"]').click();
 assert.match(await page.locator('.mv-feedback').textContent(),/Correct prediction/);
 await page.goto(base+'foundation.html#C3/c3-expect',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="indicators"]').selectOption('4');
 await page.locator('[data-mv-action="next"]').click();
 await page.locator('[data-mv-action="next"]').click();
 await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/1.60/);
 assert.match(await page.locator('.mv-question').textContent(),/4 red and 1 blue/);
 await page.goto(base+'foundation.html#C3/c3-variance',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="sampling-n"]').selectOption('400');
 await page.locator('[data-mv-param="sampling-p"]').selectOption('0.1');
 await page.locator('[data-mv-action="next"]').click();
 await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/0.0150/);
 assert.match(await page.locator('.mv-svg').textContent(),/n=400/);
 await page.goto(base+'foundation.html#C3/c3-linear',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="matrix-transform"]').selectOption('rotate');
 await page.locator('[data-mv-param="matrix-vector"]').selectOption('1,2');
 for(let i=0;i<3;i++)await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/\(-2, 1\)/);
 await page.goto(base+'foundation.html#C3/c3-opt',{waitUntil:'domcontentloaded'});
 await page.locator('[data-mv-param="gradient"]').selectOption('1');
 for(let i=0;i<3;i++)await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/196/);
 assert.match(await page.locator('.mv-explanation p').textContent(),/exceeds/);
 await page.locator('[data-mv-param="gradient"]').selectOption('0.125');
 for(let i=0;i<3;i++)await page.locator('[data-mv-action="next"]').click();
 assert.match(await page.locator('.mv-explanation p').textContent(),/0\.0000/);
 const stateBefore=await page.evaluate(()=>localStorage.getItem('mastery-foundation-v1'));
 await page.locator('[data-mv-action="answer"]').first().click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('mastery-foundation-v1')),stateBefore,
 'Visual prediction must not modify reviewed chapters or assessment records');
 await page.locator('[data-mv-action="answer-reset"]').click();
 await page.locator('[data-mv-action="play"]').click();
 assert.match(await page.locator('[data-mv-action="play"]').textContent(),/Pause/);
 await page.locator('[data-mv-action="play"]').click();
 await page.setViewportSize({width:390,height:844});
 const size=await page.evaluate(()=>({screen:innerWidth,root:document.documentElement.scrollWidth,pan:document.querySelector('.mv-canvas').scrollWidth>document.querySelector('.mv-canvas').clientWidth}));
 assert(size.root<=size.screen+3,'Math visuals must not overflow viewport: '+JSON.stringify(size));
 assert(size.pan,'Math visuals must be pannable on narrow screens');
 assert.deepEqual(errors,[],'Browser errors: '+errors.join('; '));
 await browser.close();
 console.log('PASS: six interactive C3 math labs in real Chromium; Bayes/expectation parameter truth, exact binomial sampling, matrix transform, gradient overshoot, mobile, accessibility and no fake progress.');
})().catch(e=>{console.error(e);process.exit(1)});
