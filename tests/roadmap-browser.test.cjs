'use strict';
const assert=require('node:assert/strict'),{chromium}=require('playwright');
(async()=>{
 const base='http://127.0.0.1:8897/';
 const browser=await chromium.launch({headless:true}),ctx=await browser.newContext({viewport:{width:1360,height:820},acceptDownloads:true});
 await ctx.addInitScript(()=>localStorage.setItem('mastery-theme','dark'));
 const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(String(e)));
 for(const file of ['roadmap.html','python-lab.html']){
  const response=await page.goto(base+file,{waitUntil:'domcontentloaded'});assert(response.ok(),file+' did not load');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--bg').trim()),'#0b0b0c');
  await page.setViewportSize({width:390,height:844});
  const dim=await page.evaluate(()=>({screen:innerWidth,root:document.documentElement.scrollWidth}));
  assert(dim.root<=dim.screen+3,file+' mobile overflow '+JSON.stringify(dim));
  await page.setViewportSize({width:1360,height:820});
 }
 await page.goto(base+'roadmap.html',{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('.rp-track').count(),3);
 assert.equal(await page.locator('.rp-step').count(),11);
 assert.match(await page.locator('#rpStageTitle').textContent(),/Orientation/);
 await page.locator('[data-track="ml"]').click();
 assert.match(await page.locator('.rp-track[aria-pressed="true"]').textContent(),/AI/);
 await page.locator('[data-select="M7"]').first().click();
 assert.match(await page.locator('#rpStageTitle').textContent(),/Deep learning/);
 await page.locator('[data-track="swe"]').click();
 await page.locator('[data-select="S7"]').first().click();
 assert.match(await page.locator('#rpStageTitle').textContent(),/Concurrency/);
 await page.locator('[data-track="quant"]').click();
 const first=page.locator('input[data-topic="C0:0"]');
 await first.check();
 let r=await page.evaluate(()=>JSON.parse(localStorage.getItem('mastery-roadmap-v1')));
 assert.equal(r.topics['C0:0'],true,'Topic review was not saved');
 await page.locator('[data-track="ml"]').click();assert.equal(await page.locator('input[data-topic="C0:0"]').isChecked(),true,'Shared foundation state lost');
 await page.locator('[data-track="quant"]').click();
 await page.locator('#rpPace').selectOption('sprint');
 await page.locator('[data-timer="toggle"]').click();
 r=await page.evaluate(()=>JSON.parse(localStorage.getItem('mastery-roadmap-v1')));
 assert.equal(r.session.status,'running');
 await page.reload({waitUntil:'domcontentloaded'});
 assert.match(await page.locator('#rpTimerStatus').textContent(),/running/);
 await page.locator('[data-timer="toggle"]').click();
 await page.locator('[data-timer="reset"]').click();
 await page.goto(base+'python-lab.html#sum_positive',{waitUntil:'domcontentloaded'});
 assert.match(await page.locator('#plTaskTitle').textContent(),/Sum the positive/);
 assert.equal(await page.locator('.pl-question').count(),25);
 assert.equal(await page.locator('#plEditorTitle').textContent(),'Python editor · sum_positive()');
 await page.locator('#plCode').fill('def sum_positive(values):\n    return 42');
 const s=await page.evaluate(()=>JSON.parse(localStorage.getItem('mastery-python-lab-v1')));
 assert.equal(s.drafts.sum_positive,'def sum_positive(values):\n    return 42');
 await page.locator('[data-question="gradient_step"]').click();
 assert.match(await page.locator('#plTaskTitle').textContent(),/gradient/);
 await page.locator('[data-filter="ml"]').click();
 assert(await page.locator('.pl-question').count()>=3,'ML filter must expose more than two exercises');
 assert.deepEqual(errors,[],'Unexpected page errors '+errors.join('; '));
 await browser.close();
 console.log('PASS: 3 tracks and 11-stage navigation; shared progress; persisted timer; dark-theme and mobile; 10 Python tasks and local draft persistence.');
})().catch(e=>{console.error(e);process.exit(1)});
